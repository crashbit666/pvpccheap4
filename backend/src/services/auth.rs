/// Below this length JWT_SECRET is accepted but logged as weak
/// (`openssl rand -hex 32` gives 64 characters).
const MIN_JWT_SECRET_LEN: usize = 32;

/// Values that must never be used as a signing key (old fallback, .env.example placeholder).
const FORBIDDEN_JWT_SECRETS: [&str; 2] =
    ["secret", "your-super-secret-jwt-key-change-in-production"];

/// Checks JWT_SECRET at startup so a misconfigured server refuses to run
/// instead of signing tokens with a guessable key.
pub fn ensure_jwt_secret() {
    match std::env::var("JWT_SECRET") {
        Err(_) => panic!("JWT_SECRET must be set"),
        Ok(s) if s.trim().is_empty() => panic!("JWT_SECRET must not be empty"),
        Ok(s) if FORBIDDEN_JWT_SECRETS.contains(&s.as_str()) => {
            panic!("JWT_SECRET is a placeholder value, generate one with: openssl rand -hex 32")
        }
        Ok(s) if s.len() < MIN_JWT_SECRET_LEN => log::warn!(
            "JWT_SECRET is only {} characters long, use at least {}",
            s.len(),
            MIN_JWT_SECRET_LEN
        ),
        Ok(_) => {}
    }
}

/// Signing secret for JWTs. `ensure_jwt_secret` runs at startup, so it is always set here.
fn jwt_secret() -> String {
    #[cfg(test)]
    if std::env::var("JWT_SECRET").is_err() {
        return "test-only-jwt-secret".to_string();
    }
    std::env::var("JWT_SECRET").expect("JWT_SECRET must be set")
}

#[derive(Debug, Serialize, Deserialize)]
pub struct Claims {
    pub sub: String, // Subject (User ID)
    pub exp: usize,  // Expiration
    /// User's token_version when it was signed; tokens from before it existed are 0
    #[serde(default)]
    pub ver: i32,
}

fn decode_token(req: &HttpRequest) -> Result<Claims, actix_web::Error> {
    let token_str = req
        .headers()
        .get("Authorization")
        .ok_or_else(|| ErrorUnauthorized("No Auth header"))?
        .to_str()
        .map_err(|_| ErrorUnauthorized("Invalid Auth header"))?
        .replace("Bearer ", "");

    decode::<Claims>(
        &token_str,
        &DecodingKey::from_secret(jwt_secret().as_bytes()),
        &Validation::default(),
    )
    .map(|data| data.claims)
    .map_err(|_| ErrorUnauthorized("Invalid Token"))
}

impl FromRequest for Claims {
    type Error = actix_web::Error;
    type Future = Pin<Box<dyn Future<Output = Result<Self, Self::Error>>>>;

    fn from_request(req: &HttpRequest, _payload: &mut Payload) -> Self::Future {
        let claims = decode_token(req);
        let pool = req.app_data::<web::Data<DbPool>>().cloned();
        Box::pin(async move {
            let claims = claims?;
            // A password change bumps the user's token_version and logs out
            // every other session (unit tests have no pool)
            let Some(pool) = pool else { return Ok(claims) };
            let user_id: i32 = claims
                .sub
                .parse()
                .map_err(|_| ErrorUnauthorized("Invalid Token"))?;
            let current = web::block(move || -> Option<i32> {
                let mut conn = pool.get().ok()?;
                users::table
                    .find(user_id)
                    .select(users::token_version)
                    .first(&mut conn)
                    .ok()
            })
            .await
            .map_err(|_| ErrorUnauthorized("Invalid Token"))?;
            match current {
                Some(version) if version == claims.ver => Ok(claims),
                _ => Err(ErrorUnauthorized("Session expired")),
            }
        })
    }
}

pub fn hash_password(password: &str) -> Result<String, String> {
    // A random salt is generated by the hasher
    let argon2 = Argon2::default();
    let password_hash = argon2
        .hash_password(password.as_bytes())
        .map_err(|e| e.to_string())?
        .to_string();
    Ok(password_hash)
}

pub fn verify_password(password: &str, password_hash: &str) -> Result<bool, String> {
    let parsed_hash = PasswordHash::new(password_hash).map_err(|e| e.to_string())?;
    let argon2 = Argon2::default();
    Ok(argon2
        .verify_password(password.as_bytes(), &parsed_hash)
        .is_ok())
}

pub fn create_jwt(user_id: i32, token_version: i32) -> Result<String, String> {
    let expiration = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|e| e.to_string())?
        .as_secs() as usize
        + 90 * 24 * 3600; // 90 days (3 months)

    let claims = Claims {
        sub: user_id.to_string(),
        exp: expiration,
        ver: token_version,
    };

    let secret = jwt_secret();

    encode(
        &Header::default(),
        &claims,
        &EncodingKey::from_secret(secret.as_bytes()),
    )
    .map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_hash_password_returns_valid_hash() {
        let password = "my_secure_password";
        let result = hash_password(password);

        assert!(result.is_ok());
        let hash = result.unwrap();
        assert!(!hash.is_empty());
        assert!(hash.starts_with("$argon2")); // Argon2 hash format
    }

    #[test]
    fn test_hash_password_produces_different_hashes_for_same_password() {
        let password = "my_secure_password";
        let hash1 = hash_password(password).unwrap();
        let hash2 = hash_password(password).unwrap();

        // Different salts should produce different hashes
        assert_ne!(hash1, hash2);
    }

    #[test]
    fn test_verify_password_correct() {
        let password = "my_secure_password";
        let hash = hash_password(password).unwrap();

        let result = verify_password(password, &hash);
        assert!(result.is_ok());
        assert!(result.unwrap());
    }

    #[test]
    fn test_verify_password_incorrect() {
        let password = "my_secure_password";
        let wrong_password = "wrong_password";
        let hash = hash_password(password).unwrap();

        let result = verify_password(wrong_password, &hash);
        assert!(result.is_ok());
        assert!(!result.unwrap());
    }

    #[test]
    fn test_verify_password_invalid_hash() {
        let result = verify_password("password", "invalid_hash");
        assert!(result.is_err());
    }

    #[test]
    fn test_verify_password_hashed_by_argon2_0_5() {
        // Stored users were hashed with argon2 0.5; they must still log in
        let old = "$argon2id$v=19$m=19456,t=2,p=1$Cxv+NgNdRmdLTF7aRaFdSw$JQU26j38KCvpPKoOwIbCiVK0wKm4YSMzKis3TDjX9yE";
        assert!(verify_password("compat-check", old).unwrap());
        assert!(!verify_password("compat-chec", old).unwrap());
    }

    #[test]
    fn test_create_jwt_returns_valid_token() {
        let user_id = 42;
        let result = create_jwt(user_id, 0);

        assert!(result.is_ok());
        let token = result.unwrap();
        assert!(!token.is_empty());
        // JWT has 3 parts separated by dots
        assert_eq!(token.split('.').count(), 3);
    }

    #[test]
    fn test_create_jwt_contains_correct_user_id() {
        let user_id = 123;
        let token = create_jwt(user_id, 0).unwrap();

        let secret = jwt_secret();
        let token_data = decode::<Claims>(
            &token,
            &DecodingKey::from_secret(secret.as_bytes()),
            &Validation::default(),
        )
        .unwrap();

        assert_eq!(token_data.claims.sub, "123");
    }

    #[test]
    fn test_token_carries_version_and_old_tokens_are_version_0() {
        let token = create_jwt(7, 3).unwrap();
        let claims = decode::<Claims>(
            &token,
            &DecodingKey::from_secret(jwt_secret().as_bytes()),
            &Validation::default(),
        )
        .unwrap()
        .claims;
        assert_eq!(claims.ver, 3);

        let old: Claims = serde_json::from_str(r#"{"sub":"7","exp":1}"#).unwrap();
        assert_eq!(old.ver, 0);
    }

    #[test]
    fn test_jwt_expiration_is_in_future() {
        let user_id = 1;
        let token = create_jwt(user_id, 0).unwrap();

        let secret = jwt_secret();
        let token_data = decode::<Claims>(
            &token,
            &DecodingKey::from_secret(secret.as_bytes()),
            &Validation::default(),
        )
        .unwrap();

        let now = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_secs() as usize;

        assert!(token_data.claims.exp > now);
        // Should be approximately 90 days in the future
        assert!(token_data.claims.exp <= now + 90 * 24 * 3600 + 1);
    }
}
